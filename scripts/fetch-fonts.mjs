// Downloads the app's fonts so they're served by Lifeline itself (no requests to Google from
// visitors, and fonts work offline). Run again after adding a Material Symbols icon name:
//   npm run fetch-fonts
// Inter: SIL Open Font License 1.1. Material Symbols: Apache 2.0. License texts sit next to the files.
import { Buffer } from "node:buffer";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
const OUT = new URL("../public/fonts/", import.meta.url);
const CSS = new URL("../src/fonts.css", import.meta.url);
// Scripts the app's three languages need (English, Spanish, Vietnamese).
const INTER_SUBSETS = ["latin", "latin-ext", "vietnamese"];
// Every icon name used with <Icon name="..."> (Material Symbols), alphabetical as Google requires.
const ICONS = JSON.parse(readFileSync(new URL("./material-icons.json", import.meta.url), "utf8")).sort();

const get = async (url, as = "text") => {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return as === "text" ? res.text() : Buffer.from(await res.arrayBuffer());
};

mkdirSync(OUT, { recursive: true });

// Inter is a variable font: one file per character set covers weights 400 to 800.
const interCss = await get("https://fonts.googleapis.com/css2?family=Inter:wght@400..800&display=swap");
const faces = [...interCss.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face \{([^}]+)\}/g)];
let css = "/* Generated by scripts/fetch-fonts.mjs. Don't edit by hand. */\n";
for (const [, subset, body] of faces) {
  if (!INTER_SUBSETS.includes(subset)) continue;
  const url = body.match(/url\(([^)]+)\)/)[1];
  const range = body.match(/unicode-range: ([^;]+);/)[1];
  const file = `inter-${subset}.woff2`;
  writeFileSync(new URL(file, OUT), await get(url, "bin"));
  css += `@font-face {\n  font-family: "Inter";\n  font-style: normal;\n  font-weight: 400 800;\n  font-display: swap;\n  src: url("/fonts/${file}") format("woff2");\n  unicode-range: ${range};\n}\n`;
}

const iconCss = await get(
  `https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,500,0..1,0&icon_names=${ICONS.join(",")}&display=block`,
);
writeFileSync(new URL("material-symbols.woff2", OUT), await get(iconCss.match(/url\(([^)]+)\)/)[1], "bin"));
css += `@font-face {\n  font-family: "Material Symbols Outlined";\n  font-style: normal;\n  font-weight: 500;\n  font-display: block;\n  src: url("/fonts/material-symbols.woff2") format("woff2");\n}\n`;

writeFileSync(CSS, css);
console.log(`Fonts saved to public/fonts (${INTER_SUBSETS.length} Inter subsets, ${ICONS.length} icons) and src/fonts.css written.`);
